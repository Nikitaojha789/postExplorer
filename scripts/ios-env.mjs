#!/usr/bin/env node
/**
 * Generates ios/Config/Generated/<environment>.xcconfig from `.env.<environment>`
 * so native iOS settings (bundle id suffix, display name, URL scheme) come
 * from the same source as JS and Android. Runs automatically on `pod install`
 * (Podfile pre_install). Only NATIVE-relevant keys are exported: xcconfig
 * treats `//` as a comment, so URLs are deliberately left out.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const outDir = join(root, 'ios', 'Config', 'Generated');
const ENVIRONMENTS = ['development', 'qa', 'staging', 'production'];
const NATIVE_KEYS = [
  'APP_ENV',
  'APP_DISPLAY_NAME',
  'APP_ID_SUFFIX',
  'DEEP_LINK_SCHEME',
  'DEEP_LINK_HOST',
];

const parse = text =>
  Object.fromEntries(
    text
      .split('\n')
      .map(line => line.trim())
      .filter(line => line && !line.startsWith('#') && line.includes('='))
      .map(line => {
        const index = line.indexOf('=');
        return [line.slice(0, index).trim(), line.slice(index + 1).trim()];
      }),
  );

const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
mkdirSync(outDir, { recursive: true });

for (const environment of ENVIRONMENTS) {
  const env = parse(readFileSync(join(root, `.env.${environment}`), 'utf8'));
  const lines = [
    `// GENERATED by scripts/ios-env.mjs from .env.${environment} — do not edit.`,
    `ENVFILE = .env.${environment}`,
    ...NATIVE_KEYS.map(key => `${key} = ${env[key] ?? ''}`),
    // package.json is the single source of truth for the marketing version.
    `MARKETING_VERSION = ${version}`,
  ];
  writeFileSync(join(outDir, `${environment}.xcconfig`), `${lines.join('\n')}\n`);
}
console.log(`ios-env: wrote ${ENVIRONMENTS.length} xcconfig files to ios/Config/Generated`);
